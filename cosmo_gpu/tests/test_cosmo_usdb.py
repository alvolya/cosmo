"""Stage-1 gate: USDB energies and spins agree with CoSMo (DEXHVJTcsb, this install).

References are in ``data/cosmo_usdb_reference.json`` (generated by ``data/cosmo_usdb/extract.py``
from the logs next to it). CoSMo prints energies with 6 decimals. States whose CoSMo
eigenvector error exceeds 1e-6 (an unconverged Davidson state) are not compared.
"""

import json
from pathlib import Path

import numpy as np
import pytest
import scipy.linalg as sla

from cosmo_gpu.cli import compute_levels
from cosmo_gpu.reference_csr import j_expectation, jplus_csr
from tests.systems import build_system

REF = json.loads((Path(__file__).parent / "data" / "cosmo_usdb_reference.json").read_text())
E_TOL = 6e-7  # CoSMo prints 6 decimals; inputs rounded to float32 as CoSMo reads them
E_TOL_DOUBLE = 3e-6  # full double-precision inputs: CoSMo's float32 parse shifts levels ~1e-6


@pytest.mark.parametrize("nucleus", ["18O", "19O", "20Ne"])
def test_full_spectrum_matches_cosmo(nucleus):
    ref = REF[nucleus]
    s = build_system(nucleus, cosmo_float32=True)
    assert s.basis.dim == ref["dim"]
    w, v = sla.eigh(s.H.toarray())
    np.testing.assert_allclose(w, ref["energies"], atol=E_TOL, rtol=0)
    nj = min(30, len(w))
    jp, _ = jplus_csr(s.basis)
    J = j_expectation(np.ascontiguousarray(v[:, :nj].T), jp, s.basis.m2)
    np.testing.assert_allclose(2 * J, ref["j2"][:nj], atol=1e-6)


@pytest.mark.parametrize(
    "nucleus",
    [
        "22Na",  # odd-odd
        "24Mg",
        "25Mg",
        pytest.param("26Al", marks=pytest.mark.slow),  # odd-odd
        pytest.param("28Si", marks=pytest.mark.slow),
    ],
)
def test_lowest_levels_match_cosmo(nucleus):
    ref = REF[nucleus]
    lev = compute_levels(nucleus, "sd", "usdb", nev=10, tol=1e-9, cosmo_float32=True)
    assert lev.converged
    assert lev.basis.dim == ref["dim"]
    ok = np.array(ref["vector_error"]) < 1e-6  # skip states CoSMo did not converge
    assert ok.sum() >= 6
    np.testing.assert_allclose(lev.energies[ok], np.array(ref["energies"])[ok], atol=E_TOL, rtol=0)
    np.testing.assert_allclose(2 * lev.spins[ok], np.array(ref["j2"])[ok], atol=1e-6)


def test_25mg_matches_bigstick():
    """BIGSTICK examples/sd/output/mg25ref.res: ground state -94.40128 MeV."""
    lev = compute_levels("25Mg", "sd", "usdb", nev=1, tol=1e-9)
    assert lev.energies[0] == pytest.approx(-94.40128, abs=1e-5)
    assert round(2 * lev.spins[0]) == 5


def test_double_precision_inputs_close_to_cosmo():
    lev = compute_levels("24Mg", "sd", "usdb", nev=4, tol=1e-9)
    np.testing.assert_allclose(lev.energies, REF["24Mg"]["energies"][:4], atol=E_TOL_DOUBLE, rtol=0)
